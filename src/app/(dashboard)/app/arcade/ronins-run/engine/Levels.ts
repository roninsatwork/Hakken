export interface PatrolTuning {
  speedMultiplier: number;
  awarenessMultiplier: number;
  searchSeconds: number;
}
export const STANDARD_PATROL_TUNING: Readonly<PatrolTuning> = {
  speedMultiplier: 1,
  awarenessMultiplier: 1,
  searchSeconds: 4,
};
export interface LevelDefinition extends Terrain {
  id: NightHeistLevelId;
  image: string;
  start: Point;
  exit: Point;
  treasure: Point;
  spirit: Point;
  patrolTuning?: Readonly<PatrolTuning>;
  seals: readonly Point[];
  patrols: readonly { kind: 'guard' | 'hound'; route: readonly Point[] }[];
  foreground: readonly { depth: number; polygon: Polygon }[];
}
const route = (kind: 'guard' | 'hound', points: [number, number][]) => ({
  kind,
  route: points.map(([x, y]) => ({ x, y })),
});
